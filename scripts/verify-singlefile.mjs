import { chromium } from 'playwright'
const file = process.argv[2]
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome' })
const page = await browser.newPage({ viewport: { width: 1500, height: 940 } })
const errors = []
page.on('pageerror', e => errors.push(String(e).slice(0,200)))
page.on('console', m => { if (m.type()==='error') errors.push(m.text().slice(0,200)) })
page.on('request', r => { const u=r.url(); if (!u.startsWith('file:') && !u.startsWith('data:')) errors.push('EXTERNAL REQUEST: '+u) })
await page.goto('file://' + file)
await page.waitForSelector('.library-row', { timeout: 20000 })
console.log('library rows:', await page.locator('.library-row').count())
await page.getByRole('button', { name: /Continue/ }).click()
await page.waitForTimeout(600)
console.log('city visible:', await page.locator('.city-map').isVisible())
await page.locator('.app-nav-item', { hasText: /^Location/i }).click()
await page.waitForTimeout(900)
console.log('canvas visible:', await page.locator('.loc-canvas').isVisible())
await page.getByRole('button', { name: 'Roll initiative' }).click()
await page.waitForTimeout(300)
console.log('initiative rows:', await page.locator('.loc-init-row').count())
await page.locator('.app-nav-item', { hasText: /^Forge/i }).click()
await page.waitForTimeout(700)
console.log('roster rows:', await page.locator('.forge-roster-row').count())
console.log('fonts loaded:', await page.evaluate(() => document.fonts.check('700 20px Oswald')))
await browser.close()
if (errors.length) { console.log('\nPROBLEMS:'); errors.slice(0,8).forEach(e=>console.log(' -',e)); process.exitCode=1 }
else console.log('\nno console errors, no external requests')
